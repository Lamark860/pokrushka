def seed_project(db: Session, project: Project) -> None:
    """Наполнить проект стартовой контент-ДНК. Идемпотентно: пропускает уже заполненное."""
    if project.voice is None:
        db.add(
            VoiceProfile(
                tenant_id=project.tenant_id,
                project_id=project.id,
                brand=VOICE["brand"],
                who=VOICE["who"],
                core_idea=VOICE["core_idea"],
                audience=VOICE["audience"],
                offer_cta=VOICE["offer_cta"],
                persona=VOICE["persona"],
                format_rules=VOICE["format_rules"],
                avoid_map=VOICE["avoid_map"],
                structure=VOICE["structure"],
                hashtags=VOICE["hashtags"],
                topics=VOICE["topics"],
            )
        )

    if not project.cases:
        for i, (niche, metric) in enumerate(CASES):
            db.add(
                Case(
                    tenant_id=project.tenant_id,
                    project_id=project.id,
                    niche=niche,
                    metric=metric,
                    ord=i,
                )
            )

    if not project.examples:
        for title, body in EXAMPLES:
            db.add(
                Example(
                    tenant_id=project.tenant_id,
                    project_id=project.id,
                    title=title,
                    body=body,
                    is_winner=True,
                )
            )

    db.commit()
